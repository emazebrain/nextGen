#!/usr/bin/env python3
"""
Rebuilds the placeholder picture files for In My Skin from Microsoft Fluent Emoji (MIT licence; see ../NOTICE.md).

  npm pack @lobehub/fluent-emoji-3d@1.1.0 && tar xzf lobehub-fluent-emoji-3d-1.1.0.tgz -C 3d
  npm pack @iconify-json/fluent-emoji-flat@1.2.6 && tar xzf iconify-json-fluent-emoji-flat-1.2.6.tgz -C flat
  python3 scripts/build-pictures.py 3d/package/assets flat/package/icons.json

Writes assets/<id>.webp (3D style, 256 px, transparent) and src/flat.generated.ts (2D style, inline SVG).
The lists here are the single source for which pictures ship; src/pictures.ts describes them.
"""
import colorsys, json, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

# id -> Unicode code point of the Fluent 3D picture
THREE_D = {
    # 3D objects
    "rocket": "1f680", "helicopter": "1f681", "racing-car": "1f3ce", "airplane": "2708", "locomotive": "1f682", "flying-saucer": "1f6f8",
    "sailboat": "26f5", "tractor": "1f69c", "fire-engine": "1f692", "bus": "1f68c", "motorcycle": "1f3cd", "speedboat": "1f6a4",
    # sports equipment
    "soccer-ball": "26bd", "basketball": "1f3c0", "tennis": "1f3be", "boxing-glove": "1f94a", "ping-pong": "1f3d3", "curling-stone": "1f94c",
    "softball": "1f94e", "dartboard": "1f3af", "flying-disc": "1f94f", "ice-hockey": "1f3d2", "badminton": "1f3f8", "roller-skate": "1f6fc",
    # everyday items
    "key": "1f511", "glasses": "1f453", "backpack": "1f392", "watch": "231a", "light-bulb": "1f4a1", "book": "1f4d5",
    "umbrella": "2602", "alarm-clock": "23f0", "scissors": "2702", "purse": "1f45b", "teapot": "1fad6", "pencil": "270f",
    # cartoon faces
    "lion-face": "1f981", "tiger-face": "1f42f", "robot-face": "1f916", "alien-face": "1f47d", "fox-face": "1f98a", "dragon-face": "1f432",
    "frog-face": "1f438", "bear-face": "1f43b",
}
# id -> icon name in the Fluent flat set
FLAT = {
    "guitar": "guitar", "trophy": "trophy", "crown": "crown", "gem": "gem-stone", "compass": "compass", "telescope": "telescope",
    "microscope": "microscope", "camera": "camera", "hourglass": "hourglass-done", "anchor": "anchor", "magnet": "magnet", "globe": "globe-showing-europe-africa",
}


def main(dir3d: str, flat_json: str) -> None:
    files = os.listdir(dir3d)
    os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
    for pid, cp in THREE_D.items():
        name = next((c for c in (cp + ".webp", cp + "-fe0f.webp") if c in files), None)
        if name is None:
            raise SystemExit(f"no 3D picture for {pid} ({cp})")
        im = Image.open(os.path.join(dir3d, name)).convert("RGBA").resize((256, 256), Image.LANCZOS)
        # The grey outline must look clearly different from the picture, so near-grey pictures are refused.
        px = [(r, g, b) for r, g, b, a in im.resize((48, 48)).getdata() if a >= 60]
        colour = sum(colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)[1] * max(r, g, b) / 255 for r, g, b in px) / len(px)
        if colour < 0.13:
            raise SystemExit(f"{pid} is too grey ({colour:.2f}); choose a more colourful picture")
        im.save(os.path.join(ROOT, "assets", pid + ".webp"), "WEBP", quality=85, method=6)
    icons = json.load(open(flat_json))["icons"]
    rows = []
    for pid, icon in FLAT.items():
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">{icons[icon]["body"]}</svg>'
        rows.append(f"  {json.dumps(pid)}: {json.dumps(svg)},")
    with open(os.path.join(ROOT, "src", "flat.generated.ts"), "w") as f:
        f.write("// Generated by scripts/build-pictures.py from Microsoft Fluent Emoji (flat style, MIT). Do not edit by hand.\n")
        f.write("export const FLAT_SVG: Record<string, string> = {\n" + "\n".join(rows) + "\n};\n")
    print(f"{len(THREE_D)} 3D pictures, {len(FLAT)} flat pictures")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
